-- TreXplore schema for Supabase PostgreSQL.
-- Run this file in the Supabase SQL Editor.

-- Users: travelers + admins (website management)
CREATE TABLE IF NOT EXISTS users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  email VARCHAR(150) NOT NULL UNIQUE,
  password VARCHAR(255) NOT NULL,
  bio VARCHAR(500) DEFAULT NULL,
  avatar_url VARCHAR(500) DEFAULT NULL,
  role TEXT NOT NULL DEFAULT 'traveler' CHECK (role IN ('traveler', 'admin')),
  created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

-- Destinations: tourist attractions across the 8 divisions
CREATE TABLE IF NOT EXISTS destinations (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(150) NOT NULL,
  slug VARCHAR(170) NOT NULL UNIQUE,
  division TEXT NOT NULL CHECK (division IN ('Dhaka','Chattogram','Rajshahi','Khulna','Barishal','Sylhet','Rangpur','Mymensingh')),
  district VARCHAR(100) NOT NULL,
  category VARCHAR(80) DEFAULT 'General',
  short_description VARCHAR(300),
  description TEXT,
  how_to_reach TEXT,
  best_time_to_visit VARCHAR(150),
  entry_fee VARCHAR(100) DEFAULT 'Free',
  image_url VARCHAR(500),
  latitude DECIMAL(10,6),
  longitude DECIMAL(10,6),
  created_by INT,
  created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (created_by) REFERENCES users(id) ON DELETE SET NULL
);
CREATE INDEX IF NOT EXISTS idx_division ON destinations (division);
CREATE INDEX IF NOT EXISTS idx_district ON destinations (district);

-- Blogs: travel experiences shared by users
CREATE TABLE IF NOT EXISTS blogs (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL,
  destination_id INTEGER DEFAULT NULL,
  title VARCHAR(200) NOT NULL,
  slug VARCHAR(220) NOT NULL UNIQUE,
  cover_image_url VARCHAR(500),
  content TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'published' CHECK (status IN ('published','draft')),
  created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
  FOREIGN KEY (destination_id) REFERENCES destinations(id) ON DELETE SET NULL
);

-- Comments on blogs (lightweight community layer)
CREATE TABLE IF NOT EXISTS comments (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  blog_id INTEGER NOT NULL,
  user_id INTEGER NOT NULL,
  content VARCHAR(1000) NOT NULL,
  created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (blog_id) REFERENCES blogs(id) ON DELETE CASCADE,
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

-- ---------------------------------------------------------------------------
-- AI recommendations
-- Safe to re-run on an existing database (everything is IF NOT EXISTS).
-- ---------------------------------------------------------------------------

-- Places a traveler has saved. The strongest explicit taste signal.
CREATE TABLE IF NOT EXISTS favorites (
  user_id INTEGER NOT NULL,
  destination_id INTEGER NOT NULL,
  created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (user_id, destination_id),
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
  FOREIGN KEY (destination_id) REFERENCES destinations(id) ON DELETE CASCADE
);

-- Behaviour log the recommender learns from. One row per observed action:
--   view        opened a destination page
--   blog_read   read a story about a destination
--   blog_write  published a story about a destination
--   filter      filtered the destination list by category and/or division
CREATE TABLE IF NOT EXISTS user_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL,
  destination_id INTEGER DEFAULT NULL,
  category VARCHAR(80) DEFAULT NULL,
  division VARCHAR(30) DEFAULT NULL,
  event_type TEXT NOT NULL CHECK (event_type IN ('view','blog_read','blog_write','filter')),
  created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
  FOREIGN KEY (destination_id) REFERENCES destinations(id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_events_user_time ON user_events (user_id, created_at);
CREATE INDEX IF NOT EXISTS idx_events_destination ON user_events (destination_id);
